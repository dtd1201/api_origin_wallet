        static fn (string $roleCode) => trim($roleCode),
        explode(',', (string) env('AUTH_ADMIN_ROLE_CODES', 'admin,super_admin,compliance_officer,finance_operator,operations_operator,support_agent,auditor'))
    ))),

    /*
    |--------------------------------------------------------------------------
    | Authentication Defaults
    |--------------------------------------------------------------------------
    |
